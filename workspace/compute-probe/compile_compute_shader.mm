#import <Foundation/Foundation.h>
#include <dlfcn.h>
#include <stdio.h>
#define BOOL DXC_BOOL
#include "../shader_probe_headers/dxcapi.h"
#undef BOOL

// Generates an original tiny DXIL shader and the embedded probe byte array.
// The compiler is the unchanged macOS DXC shipped in the GPTK resources.
int main(int argc, char **argv) {
    @autoreleasepool {
        if (argc != 3) {
            fprintf(stderr, "usage: compile_compute_shader <libdxcompiler.dylib> <output-header>\n");
            return 64;
        }
        void *library = dlopen(argv[1], RTLD_NOW | RTLD_LOCAL);
        if (!library) { fprintf(stderr, "DXC dlopen: %s\n", dlerror()); return 1; }
        auto create = reinterpret_cast<DxcCreateInstanceProc>(dlsym(library, "DxcCreateInstance"));
        if (!create) return 2;
        IDxcCompiler3 *compiler = nullptr;
        HRESULT status = create(CLSID_DxcCompiler, __uuidof(IDxcCompiler3), reinterpret_cast<void **>(&compiler));
        if (FAILED(status) || !compiler) return 3;
        const char *source =
            "RWByteAddressBuffer output : register(u0);\n"
            "cbuffer Parameters : register(b0) { uint wordCount; uint salt; };\n"
            "[numthreads(64,1,1)] void main(uint3 tid : SV_DispatchThreadID) {\n"
            "  if (tid.x < wordCount) output.Store(tid.x * 4, (tid.x * 2654435761u) ^ salt);\n"
            "}\n";
        DxcBuffer sourceBuffer = {source, strlen(source), DXC_CP_UTF8};
        const wchar_t *arguments[] = {L"-E", L"main", L"-T", L"cs_6_0", L"-O3"};
        IDxcResult *result = nullptr;
        status = compiler->Compile(&sourceBuffer, arguments, _countof(arguments), nullptr,
            __uuidof(IDxcResult), reinterpret_cast<void **>(&result));
        if (FAILED(status) || !result) return 4;
        IDxcBlobUtf8 *diagnostics = nullptr;
        result->GetOutput(DXC_OUT_ERRORS, __uuidof(IDxcBlobUtf8), reinterpret_cast<void **>(&diagnostics), nullptr);
        if (diagnostics) { fprintf(stderr, "%s", diagnostics->GetStringPointer()); diagnostics->Release(); }
        result->GetStatus(&status);
        if (FAILED(status)) return 5;
        IDxcBlob *shader = nullptr;
        result->GetOutput(DXC_OUT_OBJECT, __uuidof(IDxcBlob), reinterpret_cast<void **>(&shader), nullptr);
        if (!shader) return 6;
        FILE *file = fopen(argv[2], "wb");
        if (!file) return 7;
        fprintf(file, "// Generated by compile_compute_shader from the original probe HLSL.\n");
        fprintf(file, "static const unsigned char compute_shader_dxil[] = {\n");
        const auto *bytes = static_cast<const unsigned char *>(shader->GetBufferPointer());
        for (size_t i = 0; i < shader->GetBufferSize(); ++i) {
            fprintf(file, "0x%02x,%s", bytes[i], i % 16 == 15 ? "\n" : "");
        }
        fprintf(file, "\n};\n");
        if (fclose(file)) return 8;
        printf("DXC.original_probe_shader.bytes=%zu target=cs_6_0\n", shader->GetBufferSize());
        shader->Release(); result->Release(); compiler->Release();
        return 0;
    }
}
